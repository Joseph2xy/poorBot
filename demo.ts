import { evaluate, type PriceState, type PricingPolicy } from './pricing.ts';
import { priceAlert } from './notifications.ts';
import type { Offer } from './sources.ts';

// Deliberately imports no bot/tracker entrypoint: no credentials, HTTP, Discord
// connection, or persistent store are needed to explore the real decision code.
const policy: PricingPolicy = {
  minimumDropPercent: 10, minimumDropEuro: 2, checkIntervalMinutes: 60, resetAfterHours: 48,
};
const offer: Offer = {
  title: 'Example game', edition: 'Standard', merchant: 'Example Store',
  url: 'https://www.allkeyshop.com/blog/buy-elden-ring-cd-key-compare-prices/',
  price: 0,
};

console.log('OFFLINE DEMO — invented prices and store, not current offers. Nothing is sent or saved.\n');
console.log('Hourly checks; a drop must reach both 10% and €2 against the reference price.');
let previous: PriceState | undefined;
const rows = [2500, 2400, 2300, 2250, 2250, 2200, 2000].map((price, hour) => {
  const decision = evaluate(previous, price, policy, hour * 3_600_000);
  previous = decision.next;
  return {
    hour, price: `€${(price / 100).toFixed(2)}`,
    'reference before check': `€${(decision.reference / 100).toFixed(2)}`,
    result: decision.alert ? 'Alert + mention' : 'Routine update, no mention',
  };
});
console.table(rows);

const baseline = evaluate(undefined, 2500, policy, 0).next;
const decision = evaluate(baseline, 1999, policy, 3_600_000);
console.log('\nSample Discord payload, generated by the production formatter:');
console.log(JSON.stringify(priceAlert({ ...offer, price: 1999 }, decision), null, 2));
